// Matches https://www.youtube.com/... and bare https://youtube.com/...
const YT_URL_RE = /^https?:\/\/([a-z0-9-]+\.)*youtube\.com(\/.*)?$/;
const COOKIE_URLS = ["https://www.youtube.com/", "https://music.youtube.com/"];
const YT_TITLE_SUFFIX_RE = /\s*-\s*YouTube(?:\s+Music)?\s*$/;

// Human-readable descriptions for the server's `matches` values.
const MATCH_LABELS = {
  song_exact: "the same song",
  title_exact: "an exact title match",
  title_likely: "a similar title",
  artist_exact: "an exact artist match",
  artist_likely: "a similar artist",
  duration_exact: "an exact duration match",
  duration_likely: "a similar duration",
};

const btn = document.getElementById("download-btn");
const statusEl = document.getElementById("status");
const videoEl = document.getElementById("video");

let activeTabUrl = null;
let youtubeData = null;
let alreadyDownloaded = false;

// Strip characters that would corrupt the tab-separated Netscape format.
function sanitize(value) {
  return String(value).replace(/[\t\n\r]/g, " ");
}

function toCookieLine(cookie) {
  const domain = cookie.domain || ".youtube.com";
  const includeSubdomains = domain.startsWith(".") ? "TRUE" : "FALSE";
  const path = cookie.path || "/";
  const secure = cookie.secure ? "TRUE" : "FALSE";
  // Session cookies have no expirationDate -> 0 (expires at end of session).
  const expires = cookie.expirationDate ? Math.floor(cookie.expirationDate) : 0;
  const name = sanitize(cookie.name);
  const value = sanitize(cookie.value);

  return [domain, includeSubdomains, path, secure, expires, name, value].join(
    "\t",
  );
}

function toNetscapeFile(cookies) {
  const lines = [
    "# Netscape HTTP Cookie File",
    "# Generated by the YouTube to MP3 extension",
    ...cookies.sort((a, b) => a.name.localeCompare(b.name)).map(toCookieLine),
  ];
  return lines.join("\n") + "\n";
}

function isYoutubeUrl(url) {
  return typeof url === "string" && YT_URL_RE.test(url);
}

// Cookies for www.youtube.com and music.youtube.com overlap (most live on
// `.youtube.com`), so merge both sets instead of listing the same ones twice.
async function collectCookies() {
  const responses = await Promise.all(
    COOKIE_URLS.map((url) => browser.cookies.getAll({ url })),
  );
  const byIdentity = new Map();
  for (const cookie of responses.flat()) {
    const key = [
      cookie.storeId || "",
      cookie.domain || "",
      cookie.path || "/",
      cookie.name,
    ].join("\t");
    byIdentity.set(key, cookie);
  }
  return [...byIdentity.values()];
}

// Extract just the 11-character video id from a watch/shorts URL.
// Returns null for pages that are not a single video (channels, playlists).
function extractVideoId(url) {
  try {
    const parsed = new URL(url);
    return (
      parsed.searchParams.get("v") ||
      /^\/(?:shorts|live|embed)\/([\w-]{11})(?:\/|$)/.exec(
        parsed.pathname,
      )?.[1] ||
      null
    );
  } catch {
    return null;
  }
}

// Injected into the YouTube tab by `browser.scripting.executeScript`, so this
// function must not reference anything from the popup's scope.
function readPageMetadata() {
  const text = (element) => (element ? element.textContent.trim() : "");
  const content = (selector) => {
    const element = document.querySelector(selector);
    return element ? (element.getAttribute("content") || "").trim() : "";
  };
  const firstText = (selectors) => {
    for (const selector of selectors) {
      const value = text(document.querySelector(selector));
      if (value) return value;
    }
    return "";
  };

  // YouTube exposes durations as ISO 8601 (e.g. "PT4M13S").
  const isoToSeconds = (value) => {
    const match =
      /^P(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+(?:\.\d+)?)S)?)?$/.exec(
        value,
      );
    if (!match) return 0;
    const [, days, hours, minutes, seconds] = match;
    return Math.round(
      (Number(days) || 0) * 86400 +
        (Number(hours) || 0) * 3600 +
        (Number(minutes) || 0) * 60 +
        (Number(seconds) || 0),
    );
  };

  // music.youtube.com is a separate app whose watch pages do not use the
  // regular YouTube elements below. Its player bar holds the current track's
  // title, artist and time, and is populated even when document.title is just
  // "YouTube Music". These selectors simply match nothing on youtube.com.
  const musicTitle = firstText([
    "ytmusic-player-bar .title",
    "ytmusic-player-bar #song-title",
  ]);

  const musicArtist = (() => {
    const names = [];
    for (const link of document.querySelectorAll(
      "ytmusic-player-bar .byline a",
    )) {
      const href = link.getAttribute("href") || "";
      // The byline is "Artist • Album • Year"; skip album/playlist links.
      if (/\/browse\/MPRE|\/playlist(\?|$)/.test(href)) continue;
      const name = text(link);
      if (name) names.push(name);
    }
    // Multiple artists are separate links; join them the way the UI shows
    // them. Fall back to the plain text before the album bullet.
    return (
      names.join(", ") ||
      text(document.querySelector("ytmusic-player-bar .byline"))
        .split(/[•·]/)[0]
        .trim()
    );
  })();

  const title =
    musicTitle ||
    content('meta[itemprop="name"]') ||
    text(
      document.querySelector(
        "ytd-watch-metadata #title h1 yt-formatted-string",
      ),
    ) ||
    text(document.querySelector("h1.ytd-watch-metadata")) ||
    document.title.replace(/\s*-\s*YouTube(?:\s+Music)?\s*$/, "").trim();

  const artist =
    musicArtist ||
    content('#owner link[itemprop="name"]') ||
    text(document.querySelector("ytd-video-owner-renderer #channel-name a")) ||
    text(document.querySelector("#owner #channel-name a")) ||
    text(document.querySelector("ytd-channel-name a"));

  // The music player bar shows "<current> / <total>"; take the total.
  const timeInfo = firstText([
    "ytmusic-player-bar .time-info",
    "ytmusic-player-bar #time-info",
  ]);
  const timeInfoTotal = /\/\s*((?:\d+:)?\d+:\d+)\s*$/.exec(timeInfo);
  const musicDuration = timeInfoTotal
    ? timeInfoTotal[1]
        .split(":")
        .reduce((total, part) => total * 60 + Number(part), 0)
    : 0;

  const video = document.querySelector("video");
  const duration =
    isoToSeconds(content('meta[itemprop="duration"]')) ||
    musicDuration ||
    (video && Number.isFinite(video.duration) ? Math.round(video.duration) : 0);

  return { title, artist, duration };
}

async function collectYoutubeData(tab, videoId) {
  let page = null;
  try {
    const results = await browser.scripting.executeScript({
      target: { tabId: tab.id },
      func: readPageMetadata,
    });
    page = results && results[0] ? results[0].result : null;
  } catch (err) {
    // The page may still be loading; fall back to the tab title.
    console.warn("Could not read page metadata:", err);
  }

  const tabTitle = (tab.title || "").replace(YT_TITLE_SUFFIX_RE, "").trim();

  return {
    youtube_slug: videoId,
    title: (page && page.title) || tabTitle || activeTabUrl,
    artist: (page && page.artist) || "",
    duration_seconds: (page && page.duration) || 0,
  };
}

function setStatus(message, level) {
  statusEl.classList.remove("error", "success", "warning");
  if (level) {
    statusEl.classList.add(level);
  }
  statusEl.textContent = message;
}

function setDownloadEnabled(enabled) {
  btn.disabled = !enabled || alreadyDownloaded;
}

async function checkExists() {
  if (!youtubeData) return;

  setStatus("Checking your library…");
  setDownloadEnabled(false);

  let result;
  try {
    result = await browser.runtime.sendMessage({
      type: "exists",
      youtubeData,
    });
  } catch (err) {
    console.warn("Exists check failed:", err);
    setStatus("Could not check whether this is already downloaded.");
    setDownloadEnabled(true);
    return;
  }

  if (!result || !result.ok) {
    setStatus(
      "Could not check whether this is already downloaded." +
        (result && result.status ? ` (server returned ${result.status})` : ""),
    );
    setDownloadEnabled(true);
    return;
  }

  const matches =
    result.body && Array.isArray(result.body.matches)
      ? result.body.matches
      : [];
  const verdict =
    result.body && Number(result.body.verdict) ? result.body.verdict : 0;

  // The server only returns `song_exact` for a video that was downloaded
  // before, so that is the one case where downloading must be blocked.
  if (matches.includes("song_exact")) {
    alreadyDownloaded = true;
    setStatus("Already downloaded — this video is in your library.", "error");
    setDownloadEnabled(false);
    return;
  }

  if (matches.length > 0 || verdict > 0) {
    const details = matches.length
      ? matches.map((match) => MATCH_LABELS[match] || match).join(", ")
      : `match score ${verdict}`;
    setStatus(
      `Possible duplicate found (${details}). You can still download it.`,
      "warning",
    );
  } else {
    setStatus("");
  }

  setDownloadEnabled(true);
}

async function init() {
  try {
    const [tab] = await browser.tabs.query({
      active: true,
      currentWindow: true,
    });
    activeTabUrl = tab && tab.url ? tab.url : null;
    const videoId = extractVideoId(activeTabUrl);

    if (!isYoutubeUrl(activeTabUrl) || !videoId) {
      videoEl.textContent = "Open a YouTube video to convert it.";
      setDownloadEnabled(false);
      return;
    }

    videoEl.textContent = tab.title || activeTabUrl;
    videoEl.title = activeTabUrl;
    setDownloadEnabled(false);

    youtubeData = await collectYoutubeData(tab, videoId);
    // On music.youtube.com the tab title is often just "YouTube Music", so
    // prefer the metadata read from the page.
    if (youtubeData.title) {
      videoEl.textContent = youtubeData.artist
        ? `${youtubeData.title} — ${youtubeData.artist}`
        : youtubeData.title;
    }
    await checkExists();
  } catch (err) {
    console.error("Could not read the active tab:", err);
    videoEl.textContent = "Could not read the current tab.";
    setDownloadEnabled(false);
  }
}

async function downloadMp3() {
  if (!youtubeData || alreadyDownloaded) {
    setStatus("This video cannot be downloaded.");
    return;
  }

  setDownloadEnabled(false);
  setStatus("Reading cookies…");

  try {
    // The cookies API returns httpOnly cookies too (page JS cannot, but
    // privileged extension code can).
    const cookies = await collectCookies();

    if (cookies.length === 0) {
      setStatus("No cookies found for youtube.com.", "error");
      return;
    }

    const cookiesTxt = toNetscapeFile(cookies);
    const httpOnlyCount = cookies.filter((c) => c.httpOnly).length;
    setStatus(`Sending ${cookies.length} cookies (${httpOnlyCount} httpOnly)…`);

    const result = await browser.runtime.sendMessage({
      type: "download",
      cookies: cookiesTxt,
      youtubeData,
    });

    console.log("[yt-mp3] popup result:", result);

    if (!result) {
      setStatus("No response from the extension background.", "error");
    } else if (result.ok) {
      if (
        result.body &&
        result.body.message === "This audio was already downloaded"
      ) {
        alreadyDownloaded = true;
        setStatus("This audio was already downloaded.", "warning");
      } else {
        setStatus("Success! MP3 conversion started.", "success");
      }
    } else {
      setStatus(
        `Server error (${result.status}): ` +
          JSON.stringify(result.body, null, 2),
        "error",
      );
    }
  } catch (err) {
    console.error("Request failed:", err);
    setStatus("Request failed: " + err.message, "error");
  } finally {
    setDownloadEnabled(true);
  }
}

btn.addEventListener("click", downloadMp3);
init();
